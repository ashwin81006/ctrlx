package com.ctrlx.server;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.BufferedReader;
import java.io.InputStreamReader;
import java.io.PrintWriter;
import java.net.ServerSocket;
import java.net.Socket;
import java.nio.charset.StandardCharsets;
import java.util.concurrent.atomic.AtomicReference;

import org.junit.jupiter.api.Test;

public class ProtocolTest {
    private static final String HOST = "127.0.0.1";
    private static int testPort;

    @Test
    public void testProtocolSuite() throws Exception {
        runAllTests();
    }

    public static void main(String[] args) throws Exception {
        runAllTests();
    }

    private static void runAllTests() throws Exception {
        System.out.println("=== Starting CTRLX Protocol v1.1 Verification Suite ===");

        // Capture PIN generated by server for automated verification
        AtomicReference<String> lastGeneratedPin = new AtomicReference<>();
        Server.pairingManager.addListener((deviceId, deviceName, pin) -> {
            lastGeneratedPin.set(pin);
        });

        // Start isolated test server on dynamic ephemeral port (avoids collision with running app)
        ServerSocket testServer = new ServerSocket(0);
        testPort = testServer.getLocalPort();
        Thread serverThread = new Thread(() -> {
            try {
                while (!testServer.isClosed()) {
                    Socket socket = testServer.accept();
                    Server.pool.submit(() -> Server.handleClient(socket));
                }
            } catch (Exception ignored) {
            }
        });
        serverThread.setDaemon(true);
        serverThread.start();

        // Test 1: Handshake, PING, UNKNOWN, MALFORMED
        System.out.println("\n[Test 1] Baseline Handshake & Messages");
        try (Socket socket = new Socket(HOST, testPort);
             BufferedReader in = createReader(socket);
             PrintWriter out = createWriter(socket)) {

            out.println("{\"type\":\"HELLO\",\"version\":1}");
            String handshake = in.readLine();
            assertContains(handshake, "WELCOME", "Handshake failed");
            System.out.println("  ✓ Handshake: " + handshake);

            out.println("{\"type\":\"PING\"}");
            String ping = in.readLine();
            assertContains(ping, "PONG", "PING failed");
            System.out.println("  ✓ PING: " + ping);

            out.println("{\"type\":\"UNKNOWN\"}");
            String unknown = in.readLine();
            assertContains(unknown, "Unsupported message", "Unknown message failed");
            System.out.println("  ✓ Unknown message: " + unknown);

            out.println("{invalid json}");
            String malformed = in.readLine();
            assertContains(malformed, "Invalid JSON object", "Malformed JSON test failed");
            System.out.println("  ✓ Malformed JSON: " + malformed);
        }

        // Test 2: Unauthenticated STATS & Control Commands Must Be Rejected
        System.out.println("\n[Test 2] Unauthenticated Authorization Enforcements");
        try (Socket socket = new Socket(HOST, testPort);
             BufferedReader in = createReader(socket);
             PrintWriter out = createWriter(socket)) {

            out.println("{\"type\":\"HELLO\",\"version\":1}");
            in.readLine(); // WELCOME

            out.println("{\"type\":\"STATS\"}");
            String statsResp = in.readLine();
            assertContains(statsResp, "AUTH_REQUIRED", "STATS should require authentication");
            System.out.println("  ✓ Unauthenticated STATS rejected: " + statsResp);

            out.println("{\"type\":\"MOUSE_MOVE\",\"dx\":10,\"dy\":-5}");
            String controlResp = in.readLine();
            assertContains(controlResp, "AUTH_REQUIRED", "Control commands must require authentication");
            System.out.println("  ✓ Unauthenticated control command rejected: " + controlResp);
        }

        // Test 3: Oversized Message Buffer Protection (>4096 bytes)
        System.out.println("\n[Test 3] Oversized Message Buffer Protection");
        try (Socket socket = new Socket(HOST, testPort);
             BufferedReader in = createReader(socket);
             PrintWriter out = createWriter(socket)) {

            out.println("{\"type\":\"HELLO\",\"version\":1}");
            in.readLine();

            StringBuilder large = new StringBuilder("{\"type\":\"PING\",\"padding\":\"");
            for (int i = 0; i < 4100; i++) {
                large.append('A');
            }
            large.append("\"}");
            out.println(large.toString());

            String largeResp = in.readLine();
            assertContains(largeResp, "PAYLOAD_TOO_LARGE", "Oversized payload was not rejected");
            System.out.println("  ✓ Oversized payload rejected: " + largeResp);
        }

        // Test 4: Complete Pairing Flow (PIN Generation, Wrong PIN, Correct PIN, Token Issuance)
        System.out.println("\n[Test 4] Device Pairing Flow");
        String issuedToken;
        String testDeviceId = "phone-unit-test-101";

        try (Socket socket = new Socket(HOST, testPort);
             BufferedReader in = createReader(socket);
             PrintWriter out = createWriter(socket)) {

            out.println("{\"type\":\"HELLO\",\"version\":1}");
            in.readLine();

            // Request pairing
            out.println("{\"type\":\"PAIR_REQUEST\",\"deviceId\":\"" + testDeviceId + "\",\"deviceName\":\"Android Test Phone\"}");
            String pairReqResp = in.readLine();
            assertContains(pairReqResp, "PAIR_PIN_REQUIRED", "Pair request failed");
            System.out.println("  ✓ PAIR_REQUEST: " + pairReqResp);

            String generatedPin = lastGeneratedPin.get();
            if (generatedPin == null) {
                generatedPin = Server.pairingManager.getPendingPinForTesting(testDeviceId);
            }
            if (generatedPin == null || !generatedPin.matches("^[0-9]{6}$")) {
                throw new AssertionError("PIN was not generated properly: " + generatedPin);
            }
            System.out.println("  ✓ Server generated 6-digit PIN securely");

            // Verify with incorrect PIN
            out.println("{\"type\":\"PAIR_VERIFY\",\"deviceId\":\"" + testDeviceId + "\",\"pin\":\"000000\"}");
            String wrongPinResp = in.readLine();
            assertContains(wrongPinResp, "INVALID_PIN", "Wrong PIN was not rejected");
            System.out.println("  ✓ Incorrect PIN rejected: " + wrongPinResp);

            // Verify with correct PIN
            out.println("{\"type\":\"PAIR_VERIFY\",\"deviceId\":\"" + testDeviceId + "\",\"pin\":\"" + generatedPin + "\"}");
            String correctPinResp = in.readLine();
            assertContains(correctPinResp, "PAIR_SUCCESS", "Pairing verify failed with valid PIN");
            JsonObject successObj = JsonParser.parseString(correctPinResp).getAsJsonObject();
            issuedToken = successObj.get("token").getAsString();
            if (issuedToken == null || issuedToken.isEmpty()) {
                throw new AssertionError("Token not received in PAIR_SUCCESS");
            }
            System.out.println("  ✓ Valid PIN accepted & Auth token issued");

            // Authenticated STATS should now succeed on this session
            out.println("{\"type\":\"STATS\"}");
            String authStats = in.readLine();
            assertContains(authStats, "connectedClients", "Authenticated STATS failed");
            System.out.println("  ✓ Authenticated STATS succeeded: " + authStats);

            // Test authenticated mouse operations
            out.println("{\"type\":\"MOUSE_MOVE\",\"dx\":15,\"dy\":-10}");
            out.println("{\"type\":\"MOUSE_CLICK\",\"button\":\"LEFT\",\"action\":\"CLICK\"}");
            out.println("{\"type\":\"MOUSE_CLICK\",\"button\":\"RIGHT\",\"action\":\"CLICK\"}");
            out.println("{\"type\":\"MOUSE_SCROLL\",\"amount\":-3}");
            out.println("{\"type\":\"PING\"}"); // Flush and verify session is still healthy
            String healthPong = in.readLine();
            assertContains(healthPong, "PONG", "Session unhealthy after mouse commands");
            System.out.println("  ✓ Authenticated mouse move, clicks, and scroll executed successfully");
        }

        // Test 5: Mandatory PIN Pairing Architecture (Disconnect invalidates previous token, reconnect requires fresh PIN)
        System.out.println("\n[Test 5] Disconnect Token Invalidation & Mandatory Re-Pairing Flow");
        // Sub-test 5a: Previous session token is invalidated upon disconnect
        try (Socket socket = new Socket(HOST, testPort);
             BufferedReader in = createReader(socket);
             PrintWriter out = createWriter(socket)) {

            out.println("{\"type\":\"HELLO\",\"version\":1}");
            in.readLine();

            out.println("{\"type\":\"AUTH\",\"deviceId\":\"" + testDeviceId + "\",\"token\":\"" + issuedToken + "\"}");
            String invalidAuth = in.readLine();
            assertContains(invalidAuth, "AUTH_FAILED", "Previous token should be invalidated upon disconnect");
            System.out.println("  ✓ Disconnect successfully invalidated token: " + invalidAuth);
        }

        // Sub-test 5b: Reconnect requires fresh PAIR_REQUEST and PIN verification
        try (Socket socket = new Socket(HOST, testPort);
             BufferedReader in = createReader(socket);
             PrintWriter out = createWriter(socket)) {

            out.println("{\"type\":\"HELLO\",\"version\":1}");
            in.readLine();

            out.println("{\"type\":\"PAIR_REQUEST\",\"deviceId\":\"" + testDeviceId + "\",\"deviceName\":\"Android Test Phone\"}");
            String pairReqResp = in.readLine();
            assertContains(pairReqResp, "PAIR_PIN_REQUIRED", "Reconnection pair request failed");
            System.out.println("  ✓ Reconnection requires fresh PIN: " + pairReqResp);

            String rePin = lastGeneratedPin.get();
            if (rePin == null) {
                rePin = Server.pairingManager.getPendingPinForTesting(testDeviceId);
            }
            out.println("{\"type\":\"PAIR_VERIFY\",\"deviceId\":\"" + testDeviceId + "\",\"pin\":\"" + rePin + "\"}");
            String rePairResp = in.readLine();
            assertContains(rePairResp, "PAIR_SUCCESS", "Reconnection PIN verify failed");
            System.out.println("  ✓ Fresh PIN verified and reconnected: " + rePairResp);

            // Test explicit unpair
            out.println("{\"type\":\"UNPAIR\"}");
            String unpairResp = in.readLine();
            assertContains(unpairResp, "UNPAIR_SUCCESS", "Unpair failed");
            System.out.println("  ✓ Device unpairing: " + unpairResp);
        }

        // Sub-test 5c: Verify explicit unpair revokes token
        try (Socket socket = new Socket(HOST, testPort);
             BufferedReader in = createReader(socket);
             PrintWriter out = createWriter(socket)) {

            out.println("{\"type\":\"HELLO\",\"version\":1}");
            in.readLine();

            out.println("{\"type\":\"AUTH\",\"deviceId\":\"" + testDeviceId + "\",\"token\":\"" + issuedToken + "\"}");
            String postUnpairAuth = in.readLine();
            assertContains(postUnpairAuth, "AUTH_FAILED", "Revoked token should fail authentication");
            System.out.println("  ✓ Revoked token rejected after unpair: " + postUnpairAuth);
        }
        try {
            testServer.close();
        } catch (Exception ignored) {
        }

        System.out.println("\n=== ALL PROTOCOL TESTS PASSED SUCCESSFULLY! ===");
    }

    private static boolean isPortFree(int port) {
        try (ServerSocket s = new ServerSocket(port)) {
            return s.isBound();
        } catch (Exception e) {
            return false;
        }
    }

    private static BufferedReader createReader(Socket s) throws Exception {
        return new BufferedReader(new InputStreamReader(s.getInputStream(), StandardCharsets.UTF_8));
    }

    private static PrintWriter createWriter(Socket s) throws Exception {
        return new PrintWriter(s.getOutputStream(), true, StandardCharsets.UTF_8);
    }

    private static void assertContains(String actual, String expectedSubstring, String errorMsg) {
        if (actual == null || !actual.contains(expectedSubstring)) {
            throw new AssertionError(errorMsg + ". Expected to contain '" + expectedSubstring + "' but got: " + actual);
        }
    }
}
